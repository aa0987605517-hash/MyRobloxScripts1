-- One-shot installer: writes a loader stub into the executor's autoexec folder.
-- Paste this into your executor's console and press execute ONCE.
-- Uses print/warn (visible in F9 Developer Console) instead of notifications
-- so it works even on executors that block StarterGui notifications.

local LOADER_URL =
    "https://raw.githubusercontent.com/aa0987605517-hash/MyRobloxScripts1/claude/loving-edison-7k2co2/loader.lua"

-- Common autoexec folder names across executors (Synapse, Fluxus, KRNL, Celery,
-- Hydrogen, Delta, Codex, Arceus, etc.). We'll try each in turn.
local CANDIDATES = {
    "autoexec",
    "auto_execute",
    "autoexecute",
    "autoexec/scripts",
    "workspace/autoexec",
    "scripts",
}
local FILENAME = "nebula_loader.lua"

-- Tag every log so you can see them in F9 Developer Console (Client)
local function log(msg) print("[Installer] " .. tostring(msg)) end
local function err(msg) warn("[Installer] " .. tostring(msg)) end

log("starting")

-- ── Feature detection ──────────────────────────────────────────────────────
if type(writefile) ~= "function" then
    err("your executor does not expose writefile - cannot install automatically")
    err("manually paste this into your autoexec folder as a .lua file:")
    print('loadstring(game:HttpGet("' .. LOADER_URL .. '"))()')
    return
end

local hasIsfolder = (type(isfolder) == "function")
local hasMakefolder = (type(makefolder) == "function")
log(("features: writefile=yes isfolder=%s makefolder=%s"):format(
    tostring(hasIsfolder), tostring(hasMakefolder)))

-- ── Pick a target folder ────────────────────────────────────────────────────
local target
for _, dir in ipairs(CANDIDATES) do
    local exists = false
    if hasIsfolder then
        pcall(function() exists = isfolder(dir) end)
    end
    if exists then
        target = dir
        log("found existing folder: " .. dir)
        break
    end
end

if not target then
    target = CANDIDATES[1]  -- fall back to "autoexec"
    log("no existing autoexec folder; creating: " .. target)
    if hasMakefolder then
        pcall(makefolder, target)
    end
end

-- ── Write the loader stub ───────────────────────────────────────────────────
local body = string.format(
    [[-- Auto-generated by Nebula installer; safe to edit if you know what you're doing.
task.spawn(function()
    if not game:IsLoaded() then game.Loaded:Wait() end
    local ok, result = pcall(function()
        return loadstring(game:HttpGet(%q))
    end)
    if not ok or not result then
        warn("[Nebula] loader fetch failed: " .. tostring(result))
        return
    end
    local runOk, runErr = pcall(result)
    if not runOk then warn("[Nebula] loader run failed: " .. tostring(runErr)) end
end)
]],
    LOADER_URL
)

local path = target .. "/" .. FILENAME
local ok, writeErr = pcall(writefile, path, body)
if not ok then
    err("writefile failed on " .. path .. ": " .. tostring(writeErr))
    err("try one of these paths manually: " .. table.concat(CANDIDATES, ", "))
    return
end

log("installed to: " .. path)
log("content length: " .. #body .. " bytes")

-- ── Verify ──────────────────────────────────────────────────────────────────
if type(isfile) == "function" then
    local verified = false
    pcall(function() verified = isfile(path) end)
    log("verify (isfile): " .. tostring(verified))
end

log("DONE - relaunch Roblox to auto-load, OR run loader.lua now by pasting:")
print('loadstring(game:HttpGet("' .. LOADER_URL .. '"))()')
